/**
 * Phase 2G.4 end to end on the memory repository with the FREE mock image models (no provider spend, no 3D set, no
 * GPU): Yumeko's Continuity Lock → selected on a Shot → a Production Frame candidate is generated from the LOCKED
 * references → promoted → the master Look is edited (the locked Shot keeps its truth) → the Shot switches to Lock B
 * (the frame and the candidate go stale). Plus: reference overflow BLOCKS (no attempt, no job, nothing truncated).
 */
vi.setConfig({ testTimeout: 90_000, hookTimeout: 90_000 });

const mock = (modelId: string): CandidateSelection => ({ provider: "mock", modelId });

/** ProjectData exactly as the server loaders attach it. */
async function attached(h: Harness): Promise<ProjectData> {
  const data = await h.data();
  const pf = await h.repo.productionFrames.listForProject(data.project.id);
  const lv = await h.repo.locationViews.listForProject(data.project.id);
  const cc = await h.repo.characterContinuity.listForProject(data.project.id);
  return {
    ...data,
    productionFrames: pf.frames,
    productionFrameSelections: pf.selections,
    locationViews: lv.views,
    shotLocationViewSelections: lv.selections,
    characterContinuityLocks: cc.locks,
    shotCharacterContinuitySelections: cc.selections,
  };
}

async function generate(h: Harness, shotId: string, selections: CandidateSelection[]) {
  return submitCandidateSet({
    data: await attached(h),
    shotId,
    registry: h.registry,
    config: h.config,
    generation: h.repo.generation,
    candidates: h.repo.candidates,
    selections,
    acknowledgeAll: true,
    confirmedTotalUsd: null,
    title: "Frame candidates",
    purpose: "character continuity",
    userId: null,
    projectRevision: null,
    generationPurpose: "production_frame",
    now: h.clock.now,
  });
}

async function drain(h: Harness, rounds = 14) {
  for (let i = 0; i < rounds; i++) {
    await h.worker().tick(10);
    h.clock.advance(2000);
  }
}

const refsOf = (a: { request: unknown }) =>
  (a.request as { references?: Array<{ role: string; assetId: string; label: string }> }).references ?? [];

/** Real stored images (generated by the free mock model on an unrelated Shot) to use as reference evidence. */
async function storedImages(h: Harness, n: number): Promise<Asset[]> {
  const data = await h.data();
  const donor = data.shots.find((s) => s.shotCode === "1A")!;
  await h.repo.upsert(data.project.id, "shots", {
    ...donor,
    composition: { ...donor.composition, aspectRatio: "16:9" },
  });
  await generate(
    h,
    donor.id,
    Array.from({ length: n }, () => mock("mock-image-1")),
  );
  await drain(h);
  const attempts = (await h.data()).attempts.filter((a) => a.shotId === donor.id);
  return Promise.all(
    attempts.map(async (a) => (await h.repo.generation.getAttemptView(a.id))!.outputs[0]!.asset),
  );
}

async function setup() {
  const h = makeHarness();
  const data = await h.data();
  const pid = data.project.id;
  const images = await storedImages(h, 6);
  const yumeko = data.characters.find((c) => c.name === "Yumeko")!;
  // Shot 4C: Yumeko in her Formal Black Look; 16:9 so the free models are native
  const shot = data.shots.find((s) => s.shotCode === "4C")!;
  await h.repo.upsert(pid, "shots", {
    ...shot,
    composition: { ...shot.composition, aspectRatio: "16:9" },
    updatedAt: new Date(h.clock.now.getTime() - 1000).toISOString(),
  });
  // the editable source library: real front + profile identity images, one Look image
  const now = await h.data();
  const front = now.identityRefs.find((r) => r.characterId === yumeko.id && r.slot === "front")!;
  const profile = now.identityRefs.find((r) => r.characterId === yumeko.id && r.slot === "profile")!;
  await h.repo.upsert(pid, "identityRefs", { ...front, assetId: images[0]!.id });
  await h.repo.upsert(pid, "identityRefs", { ...profile, assetId: images[1]!.id });
  const look = now.looks.find((l) => l.id === shot.characters[0]!.lookId)!;
  await h.repo.upsert(pid, "looks", { ...look, referenceAssetIds: [images[2]!.id] });
  return { h, pid, shotId: shot.id, yumekoId: yumeko.id, lookId: look.id, images };
}

/** Creates a Lock from the CURRENT library (the server action's path) and returns it. */
async function createLock(h: Harness, characterId: string, lookId: string, name: string) {
  const data = await attached(h);
  const r = draftCharacterContinuityLock({
    id: randomUUID(),
    now: h.clock.now.toISOString(),
    userId: null,
    projectId: data.project.id,
    name,
    character: data.characters.find((c) => c.id === characterId)!,
    look: data.looks.find((l) => l.id === lookId)!,
    identityRefs: data.identityRefs.filter((x) => x.characterId === characterId),
    assets: data.assets,
  });
  if (!r.ok) throw new Error(r.message);
  return (await h.repo.characterContinuity.create(r.draft)).lock;
}

describe("Character Continuity (memory, free mock image models)", () => {
  it("Lock → select → mock PF candidate from LOCKED refs → promote → master edit keeps truth → Lock B stales", async () => {
    const { h, pid, shotId, yumekoId, lookId, images } = await setup();
    const assetsBefore = (await h.data()).assets.length;
    const lockA = await createLock(h, yumekoId, lookId, "Yumeko — Formal Black v1");
    expect((await h.data()).assets.length).toBe(assetsBefore); // no bytes copied
    await h.repo.characterContinuity.selectForAssignment({
      projectId: pid,
      shotId,
      characterId: yumekoId,
      continuityLockId: lockA.id,
      userId: null,
      now: h.clock.now.toISOString(),
      expectedSelectedLockId: null,
    });

    // ── generate a FREE mock Production Frame candidate ──
    const out = await generate(h, shotId, [mock("mock-image-1")]);
    expect(out.submitted).toBe(1);
    await drain(h);
    const candidate = (await h.data()).attempts.filter((a) => a.shotId === shotId)[0]!;
    expect(candidate.status).toBe("succeeded");
    const refs = refsOf(candidate);
    expect(refs.filter((r) => r.role === "identity").map((r) => r.assetId)).toEqual([
      images[0]!.id,
      images[1]!.id,
    ]);
    expect(refs.filter((r) => r.role === "character_look").map((r) => r.assetId)).toEqual([images[2]!.id]);
    expect(refs.find((r) => r.role === "identity")?.label).toBe(
      'Yumeko identity — front (Continuity Lock "Yumeko — Formal Black v1")',
    );
    const snap = candidate.packageSnapshot as {
      version: number;
      references: { characterContinuity?: Array<{ lockId: string; lockFingerprint: string }> };
    };
    expect(snap.version).toBe(5);
    expect(snap.references.characterContinuity?.map((l) => [l.lockId, l.lockFingerprint])).toEqual([
      [lockA.id, lockA.lockFingerprint],
    ]);
    expect(candidateInputBasis(candidate).characterContinuityReferences).toEqual([
      {
        characterId: yumekoId,
        lockId: lockA.id,
        lockFingerprint: lockA.lockFingerprint,
        sentAssetIds: [images[0]!.id, images[1]!.id, images[2]!.id],
      },
    ]);

    // ── promote it ──
    const promoted = await promoteGeneratedFrame(
      { frames: h.repo.productionFrames, generation: h.repo.generation, qa: h.repo.mediaQa },
      buildShotContext(await attached(h), shotId),
      { attemptId: candidate.id, userId: null },
    );
    const fresh = (d: ProjectData) =>
      productionFrameFreshness(buildShotContext(d, shotId), promoted.frame).status;
    expect(fresh(await attached(h))).toBe("fresh");

    // ── edit the MASTER Look and identity library: the locked Shot keeps its truth ──
    const before = assembleGenerationPackage(buildShotContext(await attached(h), shotId));
    const lib = await h.data();
    const look = lib.looks.find((l) => l.id === lookId)!;
    await h.repo.upsert(pid, "looks", {
      ...look,
      wardrobe: "ivory tailored suit",
      hair: "loose waves",
      referenceAssetIds: [...look.referenceAssetIds, images[3]!.id],
    });
    const front = lib.identityRefs.find((r) => r.characterId === yumekoId && r.slot === "front")!;
    await h.repo.upsert(pid, "identityRefs", { ...front, assetId: images[4]!.id });
    const after = assembleGenerationPackage(buildShotContext(await attached(h), shotId));
    expect(after.characters).toEqual(before.characters);
    expect(after.provenance.parts.characters).toBe(before.provenance.parts.characters);
    expect(after.provenance.parts.looks).toBe(before.provenance.parts.looks);
    expect(fresh(await attached(h))).toBe("fresh");
    expect(candidateInputStaleness(buildShotContext(await attached(h), shotId), candidate)).toBeNull();

    // ── switch to Lock B (made from the edited library): the frame and the candidate go stale ──
    const lockB = await createLock(h, yumekoId, lookId, "Yumeko — v2");
    expect(lockB.id).not.toBe(lockA.id);
    await expect(
      h.repo.characterContinuity.selectForAssignment({
        projectId: pid,
        shotId,
        characterId: yumekoId,
        continuityLockId: lockB.id,
        userId: null,
        now: h.clock.now.toISOString(),
        expectedSelectedLockId: null, // stale view of the pointer
      }),
    ).rejects.toThrow(/changed in the meantime/);
    await h.repo.characterContinuity.selectForAssignment({
      projectId: pid,
      shotId,
      characterId: yumekoId,
      continuityLockId: lockB.id,
      userId: null,
      now: h.clock.now.toISOString(),
      expectedSelectedLockId: lockA.id,
    });
    const ctxB = buildShotContext(await attached(h), shotId);
    expect(productionFrameFreshness(ctxB, promoted.frame)).toMatchObject({ status: "stale" });
    expect(candidateInputStaleness(ctxB, candidate)?.changed).toEqual(expect.arrayContaining(["looks"]));
    const pkgB = assembleGenerationPackage(ctxB);
    expect(pkgB.provenance.parts.overall).not.toBe(before.provenance.parts.overall);
    expect(pkgB.characters[0]!.look?.wardrobe).toBe("ivory tailored suit");

    // history is immutable: the candidate still says it was made under Lock A
    const again = (await h.data()).attempts.find((a) => a.id === candidate.id)!;
    expect(candidateInputBasis(again).characterContinuityReferences[0]!.lockId).toBe(lockA.id);
  });

  it("locked references beyond the model's limit BLOCK: no attempt, no job, nothing truncated", async () => {
    const { h, pid, shotId, yumekoId, lookId } = await setup();
    const lock = await createLock(h, yumekoId, lookId, "Yumeko — 3 images");
    expect(lock.references).toHaveLength(3);
    await h.repo.characterContinuity.selectForAssignment({
      projectId: pid,
      shotId,
      characterId: yumekoId,
      continuityLockId: lock.id,
      userId: null,
      now: h.clock.now.toISOString(),
    });
    const before = (await h.data()).attempts.length;
    // mock-image-lite accepts 2 references; the locked Character needs 3
    await expect(generate(h, shotId, [mock("mock-image-lite")])).rejects.toBeInstanceOf(
      CandidateSetBlockedError,
    );
    await expect(generate(h, shotId, [mock("mock-image-lite")])).rejects.toThrow(/accepts at most 2/);
    expect((await h.data()).attempts.length).toBe(before);
  });
});
