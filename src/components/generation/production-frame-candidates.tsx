import Link from "next/link";
import { BenchmarkBanner } from "@/components/candidates/benchmark-banner";
import { ModelComparePanel } from "@/components/candidates/model-compare-panel";
import { Badge } from "@/components/ui";
import { candidateSetPurpose } from "@/domain/generation/candidates";
import { deriveProductionFrameReferenceCandidates } from "@/domain/generation/compatibility";
import type { ProjectData } from "@/domain/schemas";
import { buildModelComparison } from "@/generation/model-comparison";
import { buildSharedEvaluation } from "@/generation/submission";
import { getCandidateRepo } from "@/server/candidates";
import { getGenerationConfig, getRegistry } from "@/server/generation";

const ROLE_LABEL: Record<string, string> = {
  production_frame: "Current Production Frame",
  storyboard: "Approved Storyboard",
  identity: "Character identity",
  character_look: "Character Look",
  location_view: "Location View",
  location: "Location reference",
  style: "Lighting reference",
  other: "Shot reference",
};

/**
 * Shot Prep → Production Frame → "Generate candidates" (Phase 2G.2). The existing model comparison and candidate-set
 * workflow, filtered to the still-image models. It does not switch the Shot to image generation: the Shot's own
 * generation modality is never touched, and nothing is generated by opening this panel (paid generation still needs
 * the server's spend gates and the person's explicit confirmation of the displayed total).
 */
export async function ProductionFrameCandidates({ data, shotId }: { data: ProjectData; shotId: string }) {
  const registry = getRegistry();
  const cfg = getGenerationConfig();
  const candidateRepo = await getCandidateRepo();
  const outcomes = await candidateRepo.listOutcomeRecords(data.project.id);
  const comparison = buildModelComparison({ data, shotId, registry, outcomes, purpose: "production_frame" });
  const shared = buildSharedEvaluation(data, shotId);
  const refs = deriveProductionFrameReferenceCandidates(shared.pkg);
  const sets = (await candidateRepo.listSets(data.project.id, { shotId, limit: 12 })).filter(
    (s) => candidateSetPurpose(s.set) === "production_frame",
  );
  const slug = data.project.slug;
  const refining = Boolean(shared.pkg.references.productionFrame);

  return (
    <div className="space-y-3" data-testid="pf-candidates-panel">
      <div className="space-y-1 text-[12px]" data-testid="pf-candidate-references">
        <div className="text-[11px] font-semibold uppercase tracking-wide text-muted">
          {refining
            ? "Images the models will start from (in priority order)"
            : "Images the models will receive"}
        </div>
        {refs.length > 0 ? (
          <ol className="list-decimal space-y-0.5 pl-5">
            {refs.map((r) => (
              <li key={r.assetId}>
                {ROLE_LABEL[r.role] ?? r.role}
                <span className="text-muted"> · {r.label}</span>
              </li>
            ))}
          </ol>
        ) : (
          <p className="text-muted" data-testid="pf-text-only">
            No stored reference images: candidates are made from the Shot&apos;s written intent alone
            (text-to-image). Nothing else has to exist first.
          </p>
        )}
        <p className="text-[11px] text-faint">
          References come only from this Shot&apos;s production data; a model that cannot take them all is
          blocked or tells you what it will not use. Nothing is cropped or sent silently.
        </p>
      </div>

      {data.project.purpose !== "production" ? <BenchmarkBanner /> : null}
      <ModelComparePanel
        projectSlug={slug}
        shotId={shotId}
        purpose="production_frame"
        rows={comparison.rows}
        historyNote={comparison.recommendation.historyNote}
        profileLabel={comparison.profileLabel}
        preference={comparison.recommendation.preference}
        coldStart={comparison.recommendation.coldStart}
        engineVersion={comparison.recommendation.engineVersion}
        maxCandidates={cfg.candidateSet.maxCandidates}
        setCeilingUsd={cfg.candidateSet.maxUsd}
        paidEnabled={cfg.paid.enabled}
      />

      {sets.length > 0 ? (
        <div className="space-y-1" data-testid="pf-candidate-sets">
          <div className="text-[11px] font-semibold uppercase tracking-wide text-muted">
            Candidate sets for this Shot
          </div>
          <ul className="space-y-0.5 text-[12px]">
            {sets.map((s) => (
              <li key={s.set.id} className="flex flex-wrap items-center gap-2">
                <Link
                  href={`/projects/${slug}/candidates/${s.set.id}`}
                  className="underline"
                  data-testid="pf-candidate-set-link"
                >
                  {s.set.title || "Production Frame candidates"}
                </Link>
                <span className="text-muted">
                  {s.members.length} image{s.members.length === 1 ? "" : "s"} ·{" "}
                  {new Date(s.set.createdAt).toLocaleString()}
                </span>
                {s.set.preferredAttemptId ? <Badge tone="accent">Best marked</Badge> : null}
              </li>
            ))}
          </ul>
        </div>
      ) : null}
    </div>
  );
}
