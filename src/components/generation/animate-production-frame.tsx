import Link from "next/link";
import { BenchmarkBanner } from "@/components/candidates/benchmark-banner";
import { ModelComparePanel } from "@/components/candidates/model-compare-panel";
import { Badge } from "@/components/ui";
import { animationFreshness, animationSource } from "@/domain/generation/animation";
import { candidateSetPurpose } from "@/domain/generation/candidates";
import type { ProjectData } from "@/domain/schemas";
import { buildModelComparison } from "@/generation/model-comparison";
import { buildSharedEvaluation } from "@/generation/submission";
import { assetUrl } from "@/lib/utils";
import { getCandidateRepo } from "@/server/candidates";
import { getGenerationConfig, getRegistry } from "@/server/generation";

const secs = (ms: number) => `${Number((ms / 1000).toFixed(2))} s`;

/**
 * Shot Prep → Animate Production Frame (Phase 2H). The canonical image-first workflow: the Shot's selected, CURRENT
 * Production Frame becomes the exact first frame of an image-to-video candidate. Reuses the model comparison and the
 * candidate-set flow (no new execution system); nothing is generated by opening this panel, a paid model is never
 * pre-selected, and spend still needs the server's gates plus an explicit confirmation of the displayed total.
 * Generic Generate (section 20) stays for text-to-video, manual start frames and reference-rich experiments.
 */
export async function AnimateProductionFrame({ data, shotId }: { data: ProjectData; shotId: string }) {
  const shared = buildSharedEvaluation(data, shotId);
  const { ctx, pkg } = shared;
  const source = animationSource(pkg);
  const selected = ctx.selectedProductionFrame;
  const slug = data.project.slug;
  const image = selected ? assetUrl(ctx.assets.get(selected.assetId)) : null;
  const cam = pkg.camera;
  const motion = [cam.movement, cam.movementSpeed && `(${cam.movementSpeed})`].filter(Boolean).join(" ");
  const beats = pkg.timing.beats;
  const override = ctx.shot.generation.startFrameAssetId;

  const candidateRepo = await getCandidateRepo();
  const sets = (await candidateRepo.listSets(data.project.id, { shotId, limit: 12 })).filter(
    (s) => candidateSetPurpose(s.set) === "animate_production_frame",
  );
  const attemptsById = new Map(data.attempts.map((a) => [a.id, a]));
  const comparison = source.ok
    ? buildModelComparison({
        data,
        shotId,
        registry: getRegistry(),
        outcomes: await candidateRepo.listOutcomeRecords(data.project.id),
        purpose: "animate_production_frame",
      })
    : null;
  const cfg = getGenerationConfig();

  return (
    <div className="space-y-3" data-testid="animate-panel" data-ready={source.ok ? "1" : "0"}>
      <p className="text-[12px] text-muted">
        The selected Production Frame becomes the <span className="text-fg">exact first frame</span> of the
        Shot&apos;s video (image-to-video only). It is never replaced by the Storyboard, a manual start frame
        or text-to-video, and the frame itself is never modified.
      </p>

      <div className="grid gap-3 md:grid-cols-[minmax(0,1fr)_minmax(0,1fr)]">
        <div className="border border-line" data-testid="animate-source">
          {selected && image ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              data-testid="animate-pf-preview"
              src={image}
              alt={`Production Frame v${selected.version} of ${ctx.shot.shotCode}`}
              className="w-full object-cover"
              style={{ aspectRatio: `${selected.width} / ${selected.height}` }}
            />
          ) : (
            <div className="flex aspect-[2.39/1] items-center justify-center bg-panel2 text-[11px] uppercase tracking-wide text-faint">
              No Production Frame selected
            </div>
          )}
          <div className="flex flex-wrap items-center gap-2 border-t border-line p-2 text-[12px]">
            <span className="font-semibold">Production Frame</span>
            {selected ? (
              <>
                <span className="font-mono" data-testid="animate-pf-version">
                  v{selected.version}
                </span>
                {pkg.references.productionFrame?.freshness === "stale" ? (
                  <Badge tone="warn">stale</Badge>
                ) : (
                  <Badge tone="pass">current</Badge>
                )}
              </>
            ) : (
              <span className="text-muted">none</span>
            )}
          </div>
        </div>
        <dl
          className="grid grid-cols-[auto_1fr] content-start gap-x-3 gap-y-1 text-[12px]"
          data-testid="animate-facts"
        >
          <dt className="text-muted">Shot duration</dt>
          <dd className="font-mono" data-testid="animate-duration">
            {pkg.timing.durationMs > 0 ? `${secs(pkg.timing.durationMs)} (${pkg.timing.source})` : "not set"}
          </dd>
          <dt className="text-muted">Camera motion</dt>
          <dd data-testid="animate-camera">{motion || "static (no movement set)"}</dd>
          <dt className="text-muted">Action</dt>
          <dd data-testid="animate-action">
            {[
              pkg.timing.beginningPose && `begins: ${pkg.timing.beginningPose}`,
              beats.length > 0 && `${beats.length} beat${beats.length === 1 ? "" : "s"}`,
              pkg.timing.endingPose && `ends: ${pkg.timing.endingPose}`,
            ]
              .filter(Boolean)
              .join(" · ") || "no action beats set"}
          </dd>
          <dt className="text-muted">Start-frame override</dt>
          <dd data-testid="animate-override">
            {!override
              ? "none"
              : selected && override === selected.assetId
                ? "set to this Production Frame (allowed)"
                : "a different image (blocks Animate)"}
          </dd>
        </dl>
      </div>

      {!source.ok ? (
        <ul className="space-y-1" data-testid="animate-blocked">
          {source.issues.map((i) => (
            <li
              key={i.code}
              data-code={i.code}
              className="border border-fail/40 bg-fail/10 p-2 text-[12px] text-fail"
            >
              {i.message}
            </li>
          ))}
        </ul>
      ) : null}

      {comparison ? (
        <>
          {data.project.purpose !== "production" ? <BenchmarkBanner /> : null}
          <ModelComparePanel
            projectSlug={slug}
            shotId={shotId}
            purpose="animate_production_frame"
            rows={comparison.rows}
            historyNote={comparison.recommendation.historyNote}
            profileLabel={comparison.profileLabel}
            preference={comparison.recommendation.preference}
            coldStart={comparison.recommendation.coldStart}
            engineVersion={comparison.recommendation.engineVersion}
            maxCandidates={cfg.candidateSet.maxCandidates}
            setCeilingUsd={cfg.candidateSet.maxUsd}
            paidEnabled={cfg.paid.enabled}
          />
        </>
      ) : null}

      {sets.length > 0 ? (
        <div className="space-y-1" data-testid="animate-sets">
          <div className="text-[11px] font-semibold uppercase tracking-wide text-muted">
            Animation candidate sets for this Shot
          </div>
          <ul className="space-y-0.5 text-[12px]">
            {sets.map((s) => {
              const from = (s.set.recommendation as { animationSource?: { version?: number } } | null)
                ?.animationSource;
              const members = s.members.flatMap((m) => {
                const a = m.attemptId ? attemptsById.get(m.attemptId) : undefined;
                return a ? [a] : [];
              });
              const stale = members.some((a) => animationFreshness(ctx, a).status !== "fresh");
              return (
                <li key={s.set.id} className="flex flex-wrap items-center gap-2" data-testid="animate-set">
                  <Link
                    href={`/projects/${slug}/candidates/${s.set.id}`}
                    className="underline"
                    data-testid="animate-set-link"
                  >
                    {s.set.title || "Animation candidates"}
                  </Link>
                  <span className="text-muted">
                    from Production Frame v{from?.version ?? "?"} · {s.members.length} clip
                    {s.members.length === 1 ? "" : "s"}
                  </span>
                  {stale ? (
                    <Badge tone="warn">stale</Badge>
                  ) : members.length > 0 ? (
                    <Badge tone="pass">current</Badge>
                  ) : null}
                  {s.set.preferredAttemptId ? <Badge tone="accent">Best marked</Badge> : null}
                </li>
              );
            })}
          </ul>
        </div>
      ) : null}
    </div>
  );
}
