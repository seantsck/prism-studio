import { createWriteStream } from "node:fs";
import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { once } from "node:events";

/**
 * TEST-ONLY generators. A production-like 3DGS Gaussian PLY is synthesized at test time (never committed, never
 * downloaded): positions over a real 3D range, varied scales and rotations, an opacity range, DC colours and
 * non-zero spherical harmonics. Written in streamed chunks so large fixtures never sit in memory.
 */

export interface FixtureGaussian {
  x: number;
  y: number;
  z: number;
  dc: [number, number, number];
  /** channel-major f_rest values (length 0, 9, 24 or 45) */
  rest: number[];
  opacity: number;
  /** log scales */
  scale: [number, number, number];
  /** (w, x, y, z), not necessarily normalized */
  rot: [number, number, number, number];
}

const REST = [0, 9, 24, 45];

/** Deterministic pseudo-random numbers (mulberry32). */
export function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A varied, realistic Gaussian (room-sized extent ±`extent` units). */
export function fixtureGaussian(i: number, shDegree: number, extent = 8, seed = 7): FixtureGaussian {
  const r = rng(seed * 1_000_003 + i);
  const u = () => r() * 2 - 1;
  return {
    x: u() * extent,
    y: u() * extent * 0.4,
    z: u() * extent,
    dc: [u() * 1.5, u() * 1.5, u() * 1.5],
    rest: Array.from({ length: REST[shDegree]! }, () => u() * 0.6),
    opacity: u() * 6,
    scale: [-1 - r() * 5, -1 - r() * 5, -1 - r() * 5],
    rot: [u() || 0.1, u(), u(), u()],
  };
}

export interface PlyWriteOptions {
  shDegree: number;
  /** property order override (names); default is the standard 3DGS order */
  order?: string[];
  /** extra float properties (e.g. nx ny nz) inserted into the record */
  extra?: string[];
  /** write these properties as double instead of float */
  doubles?: string[];
  /** override the header's format line value */
  format?: string;
  /** declared vertex count override (to fabricate truncation / trailing data) */
  declaredCount?: number;
  /** extra bytes appended after the records */
  trailing?: number;
  /** add a second element to the header */
  extraElement?: boolean;
}

export function standardOrder(shDegree: number, extra: string[] = []): string[] {
  return [
    "x",
    "y",
    "z",
    ...extra,
    "f_dc_0",
    "f_dc_1",
    "f_dc_2",
    ...Array.from({ length: REST[shDegree]! }, (_, i) => `f_rest_${i}`),
    "opacity",
    "scale_0",
    "scale_1",
    "scale_2",
    "rot_0",
    "rot_1",
    "rot_2",
    "rot_3",
  ];
}

function valueOf(g: FixtureGaussian, name: string): number {
  switch (name) {
    case "x":
      return g.x;
    case "y":
      return g.y;
    case "z":
      return g.z;
    case "opacity":
      return g.opacity;
  }
  const m = /^(f_dc|f_rest|scale|rot)_(\d+)$/.exec(name);
  if (m) {
    const k = Number(m[2]);
    if (m[1] === "f_dc") return g.dc[k]!;
    if (m[1] === "f_rest") return g.rest[k]!;
    if (m[1] === "scale") return g.scale[k]!;
    return g.rot[k]!;
  }
  return 0.25; // extra properties (normals etc.)
}

/** Streams a binary little-endian Gaussian PLY with `count` Gaussians from `gen`. */
export async function writeGaussianPly(
  file: string,
  count: number,
  gen: (i: number) => FixtureGaussian,
  o: PlyWriteOptions,
) {
  const order = o.order ?? standardOrder(o.shDegree, o.extra);
  const doubles = new Set(o.doubles ?? []);
  const header =
    "ply\n" +
    `format ${o.format ?? "binary_little_endian"} 1.0\n` +
    "comment generated by Prism tests\n" +
    `element vertex ${o.declaredCount ?? count}\n` +
    order.map((n) => `property ${doubles.has(n) ? "double" : "float"} ${n}\n`).join("") +
    (o.extraElement ? "element face 0\nproperty list uchar int vertex_indices\n" : "") +
    "end_header\n";
  const stride = order.reduce((a, n) => a + (doubles.has(n) ? 8 : 4), 0);
  const out = createWriteStream(file);
  const write = async (b: Buffer) => {
    if (!out.write(b)) await once(out, "drain");
  };
  await write(Buffer.from(header, "latin1"));
  const per = 4096;
  for (let start = 0; start < count; start += per) {
    const n = Math.min(per, count - start);
    const buf = Buffer.alloc(n * stride);
    for (let k = 0; k < n; k++) {
      const g = gen(start + k);
      let off = k * stride;
      for (const name of order) {
        const v = valueOf(g, name);
        if (doubles.has(name)) {
          buf.writeDoubleLE(v, off);
          off += 8;
        } else {
          buf.writeFloatLE(v, off);
          off += 4;
        }
      }
    }
    await write(buf);
  }
  if (o.trailing) await write(Buffer.alloc(o.trailing));
  out.end();
  await once(out, "finish");
  return { stride, headerBytes: Buffer.byteLength(header, "latin1") };
}

export async function tempDir(prefix = "prism-local-test-") {
  const dir = await mkdtemp(path.join(os.tmpdir(), prefix));
  return { dir, cleanup: () => rm(dir, { recursive: true, force: true, maxRetries: 3 }) };
}

