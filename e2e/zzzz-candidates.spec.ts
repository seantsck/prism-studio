import { expect, test, type Page } from "@playwright/test";

/**
 * Phase 2E acceptance flow, memory mode, NO paid provider and NO AI analysis: model comparison for shot 3A,
 * a three-model candidate set executed by the free MockProvider, side-by-side review, human reasons, winner,
 * explicit promotion, model history and a recommendation backed by those human outcomes. Runs last.
 * Automated continuity analysis is never started and never required.
 */
const EP = "/projects/ojousama/episodes/ep-1";
test.describe.configure({ mode: "serial" });

let setPath = "";

async function openGenerate(page: Page) {
  await page.goto(`${EP}/shots`);
  await page.getByRole("link", { name: "3A", exact: true }).click();
  await page.waitForURL(/\/shots\/[0-9a-f-]{36}/);
  const base = page.url().split("?")[0]!;
  await page.goto(`${base}?section=generate`);
  await expect(page.getByTestId("generate-workspace")).toBeVisible();
  return base;
}

const row = (page: Page, model: string) => page.locator(`[data-testid="model-row"][data-model="${model}"]`);
const card = (page: Page, label: string) =>
  page.locator(`[data-testid="candidate-card"][data-label="${label}"]`);

test("3A: the comparison matrix shows capability differences with reasons, before any spend", async ({
  page,
}) => {
  await openGenerate(page);
  const matrix = page.getByTestId("model-matrix");
  await expect(matrix).toBeVisible();
  // Runway models are present but not configured in this environment: visible, never selectable, never spent
  await expect(row(page, "gen4.5")).toBeVisible();
  await expect(row(page, "seedance2_5")).toBeVisible();
  await expect(row(page, "veo3.1")).toBeVisible();
  await expect(row(page, "gen4.5").getByTestId("model-pick")).toBeDisabled();
  await expect(row(page, "gen4.5")).toContainText("Not available here");

  // the 2.39:1 / 4.5 s shot needs explicit adaptation on a 21:9-or-16:9, whole-second model
  await expect(row(page, "gen4.5")).toHaveAttribute("data-status", "adaptation_required");
  await expect(row(page, "gen4.5")).toContainText("Framing");
  await expect(row(page, "veo3.1")).toContainText("supports 4s, 6s, 8s");

  // what Gen-4.5 receives: only the start frame is usable; every reference is shown as UNSUPPORTED
  await row(page, "gen4.5").getByRole("button", { name: "Runway Gen-4.5" }).click();
  const detail = page.getByTestId("model-detail");
  await expect(detail).toContainText("UNSUPPORTED");
  await expect(detail).toContainText("Conditions the generation");
  await expect(detail).toContainText("$0.60"); // 5 s × 12 credits × $0.01
  await row(page, "gen4.5").getByRole("button", { name: "Runway Gen-4.5" }).click();

  // Seedance: references are supported but exclusive with a first frame: the mode is a visible choice
  await row(page, "seedance2_5").getByRole("button", { name: "Seedance 2.5" }).click();
  await expect(page.getByTestId("model-detail")).toContainText("NOT USED (mode)");

  // sorting is available and costs are shown per model
  await page.getByTestId("model-sort").selectOption("cost");
  await expect(row(page, "mock-video-1").getByTestId("model-cost")).toHaveText("free");
});

test("3A: select three models, see the total, create the set; each candidate runs independently", async ({
  page,
}) => {
  test.setTimeout(180_000);
  await openGenerate(page);
  for (const m of ["mock-video-1", "mock-video-lite", "mock-video-169"]) {
    await row(page, m).getByTestId("model-pick").check();
  }
  await expect(page.getByTestId("selected-count")).toHaveText("3 selected");
  await expect(page.getByTestId("selected-total")).toContainText("free");
  // nothing is generated by selecting: the button needs the acknowledgement first
  await expect(page.getByTestId("create-candidate-set")).toBeDisabled();
  await page.getByTestId("ack-all").check();
  await expect(page.getByTestId("create-candidate-set")).toBeEnabled();
  await page.getByTestId("create-candidate-set").click();

  await page.waitForURL(/\/candidates\/[0-9a-f-]{36}/, { timeout: 30_000 });
  setPath = new URL(page.url()).pathname;
  await expect(page.getByTestId("candidate-board")).toBeVisible();
  await expect(page.getByTestId("candidate-card")).toHaveCount(3);
  await expect(page.getByTestId("set-rollup")).toContainText("3/3 completed", { timeout: 120_000 });
  for (const l of ["A", "B", "C"]) await expect(card(page, l)).toHaveAttribute("data-status", "succeeded");

  // same / different is disclosed: this is not claimed to be an identical-conditions test
  await expect(page.getByTestId("same-list")).toContainText("Production 2.39:1");
  await expect(page.getByTestId("different-list")).toContainText("Model-specific prompt wording");
  await expect(page.getByTestId("set-spend")).toContainText("free (mock)");
});

