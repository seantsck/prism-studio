test("fast human review: reject for identity, reject for motion, mark the third Best, then promote", async ({
  page,
}) => {
  test.setTimeout(120_000);
  await page.goto(setPath);

  await card(page, "A").getByTestId("review-reject").click();
  await card(page, "A").getByTestId("reject-character_identity").click();
  await expect(card(page, "A")).toHaveAttribute("data-decision", "reject", { timeout: 20_000 });
  await expect(card(page, "A").getByTestId("review-tags")).toContainText("Character identity");

  await card(page, "B").getByTestId("review-reject").click();
  await card(page, "B").getByTestId("reject-body_motion").click();
  await expect(card(page, "B")).toHaveAttribute("data-decision", "reject", { timeout: 20_000 });
  await expect(card(page, "B").getByTestId("review-tags")).toContainText("Body motion");

  await card(page, "C").getByTestId("review-best").click();
  await expect(card(page, "C")).toHaveAttribute("data-preferred", "1", { timeout: 20_000 });
  await expect(card(page, "C")).toHaveAttribute("data-decision", "approve");
  // Best does NOT promote anything
  await expect(card(page, "C")).toHaveAttribute("data-promoted", "0");

  // explicit, confirmed promotion; the losing candidates are kept
  page.once("dialog", (d) => void d.accept());
  await card(page, "C").getByTestId("promote").click();
  await expect(card(page, "C")).toHaveAttribute("data-promoted", "1", { timeout: 20_000 });
  await expect(card(page, "A")).toHaveAttribute("data-status", "succeeded");
  await expect(card(page, "B")).toHaveAttribute("data-status", "succeeded");
  await expect(page.getByTestId("set-events")).toContainText("promoted");
});

test("reload: reviews, winner and promotion persist; history keeps every step", async ({ page }) => {
  await page.goto(setPath);
  await expect(card(page, "A")).toHaveAttribute("data-decision", "reject");
  await expect(card(page, "B")).toHaveAttribute("data-decision", "reject");
  await expect(card(page, "C")).toHaveAttribute("data-promoted", "1");
  await expect(page.getByTestId("set-events")).toContainText("created");
  await expect(page.getByTestId("set-events")).toContainText("preferred set");
  // experiment history lists the set with its winner
  await page.goto(setPath.replace(/\/[0-9a-f-]{36}$/, ""));
  const exp = page.getByTestId("experiment-row").first();
  await expect(exp).toContainText("3A");
  await expect(exp).toContainText("promoted");
});

