function png(width: number, height: number, rgb: [number, number, number]): Buffer {
  const chunk = (type: string, data: Buffer) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  const raw = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y++)
    for (let x = 0; x < width; x++) raw.set(rgb, y * (width * 3 + 1) + 1 + x * 3);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const tsx = (script: string, args: string[]) =>
  execFileSync("npx", ["tsx", "--env-file=.env.local", script, ...args], {
    cwd: process.cwd(),
    env: {
      ...process.env,
      PRISM_STUDIO_PERSISTENCE: "supabase",
      PRISM_STUDIO_MOCK_STAGE_DELAY_MS: "0",
      NODE_ENV: "test",
      ...(process.env.PRISM_STUDIO_E2E_REAL_WORKER === "1"
        ? {}
        : { PRISM_STUDIO_WORKER_DEV_STORAGE: "1", PRISM_STUDIO_WORKER_DEV_ASSUME_ROLE: "1" }),
    },
    encoding: "utf8",
    timeout: 240_000,
    shell: process.platform === "win32",
  });

async function db<T>(fn: (c: pg.Client) => Promise<T>): Promise<T | null> {
  const url = process.env.SUPABASE_DB_URL ?? "";
  if (!url.includes("lyqdxiyjperhniwhzsvg")) return null; // never any other project
  const c = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await c.connect();
  try {
    return await fn(c);
  } finally {
    await c.end();
  }
}

// what this test changes in the demo project, exactly as it was
const snapshot: {
  refs: Array<{ id: string; asset_id: string | null; locked: boolean }>;
  assignment: { shot_id: string; character_id: string; look_id: string | null } | null;
} = { refs: [], assignment: null };

const scopedCleanup = () => {
  for (const [script, args] of [
    ["scripts/generation-cleanup.mts", ["--yes"]],
    ["scripts/previs-cleanup.mts", ["--yes", `--e2e-assets-prefix=${PREFIX}`]],
  ] as const) {
    try {
      tsx(script, [...args]);
    } catch {
      /* best effort; idempotent */
    }
  }
};

test.beforeAll(async () => {
  scopedCleanup();
  await db(async (c) => {
    const yumeko = (
      await c.query(
        "select ch.id from characters ch join projects p on p.id = ch.project_id where p.slug = 'ojousama' and ch.name = 'Yumeko'",
      )
    ).rows[0].id as string;
    snapshot.refs = (
      await c.query("select id, asset_id, locked from character_identity_refs where character_id = $1", [
        yumeko,
      ])
    ).rows;
    snapshot.assignment =
      (
        await c.query(
          `select sc.shot_id, sc.character_id, sc.look_id from shot_characters sc
             join shots s on s.id = sc.shot_id join projects p on p.id = s.project_id
            where p.slug = 'ojousama' and s.shot_code = '4C' and sc.character_id = $1`,
          [yumeko],
        )
      ).rows[0] ?? null;
  });
});

test.afterAll(async () => {
  await db(async (c) => {
    // the demo state first (the temporary Look can only go once no assignment uses it)
    if (snapshot.assignment)
      await c.query("update shot_characters set look_id = $3 where shot_id = $1 and character_id = $2", [
        snapshot.assignment.shot_id,
        snapshot.assignment.character_id,
        snapshot.assignment.look_id,
      ]);
    for (const r of snapshot.refs)
      // an identity upload also unlocks the slot: restore the flag too (it is part of the `characters` part)
      await c.query("update character_identity_refs set asset_id = $2, locked = $3 where id = $1", [
        r.id,
        r.asset_id,
        r.locked,
      ]);
    // this test's Locks (their images and selections cascade) and its Look; Locks are append-only for users, so this
    // runs as the database owner, scoped by this run's unique prefix
    await c.query("delete from character_continuity_locks where name like $1", [`${PREFIX}%`]);
    await c.query("delete from character_looks where name like $1", [`${PREFIX}%`]);
  });
  // mock attempts and the frame chosen from them; then this test's own uploads (and their private Storage objects)
  scopedCleanup();
  // the snapshot's own values came back (not an assumed seed value): asset and locked flag, these rows only
  const restored = await db(
    async (c) =>
      (
        await c.query("select id, asset_id, locked from character_identity_refs where id = any($1::uuid[])", [
          snapshot.refs.map((r) => r.id),
        ])
      ).rows as typeof snapshot.refs,
  );
  const byId = (rows: typeof snapshot.refs) => [...rows].sort((a, b) => a.id.localeCompare(b.id));
  if (restored) expect(byId(restored)).toEqual(byId(snapshot.refs));
});

